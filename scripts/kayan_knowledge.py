def load_catalog() -> dict[str, str]:
    rows = json.loads(DATA.read_text(encoding="utf-8"))
    out = {row["svc"]: NAME_FIX.get(row["svc"], row["name_ar"]) for row in rows}
    out.update(NAME_FIX)
    return out


