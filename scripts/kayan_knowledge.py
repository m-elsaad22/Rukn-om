def tokens_of(svc: str) -> list[str]:
    parts = [p for p in svc.lower().replace("_", "-").split("-") if p]
    extra = []
    for key in TOKENS:
        if key in svc:
            extra.append(key)
    # keep order unique
    seen = []
    for x in extra + parts:
        if x not in seen:
            seen.append(x)
    return seen


def overlay_for(svc: str) -> dict:
    merged: dict[str, list | str] = {"signs": [], "tools": [], "mistakes": [], "angle": ""}
    for tok in tokens_of(svc):
        pack = TOKENS.get(tok)
        if not pack:
            continue
        for k in ("signs", "tools", "mistakes"):
            merged[k] = list(merged[k]) + list(pack.get(k, []))
        if pack.get("angle") and not merged["angle"]:
            merged["angle"] = pack["angle"]
        elif pack.get("angle"):
            # keep first matching longest key priority already from extra list
            pass
    if not merged["angle"]:
        fam = FAMILIES[family_of(svc)]
        merged["angle"] = f"{fam['what']} بما يناسب {CATALOG.get(svc, svc)} في ظروف المدينة."
    return merged


def related_services(svc: str, limit: int = 5) -> list[str]:
    fam = family_of(svc)
    same = [s for s in CATALOG if s != svc and family_of(s) == fam]
    # stable unique order by name
    same.sort()
    # pick spread items so related lists differ across services
    if not same:
        same = [s for s in CATALOG if s != svc][:limit]
    step = max(1, len(same) // limit) if same else 1
    idx = sum(ord(c) for c in svc) % max(1, len(same))
    out = []
    for i in range(len(same)):
        out.append(same[(idx + i * step) % len(same)])
        if len(out) >= limit:
            break
    # unique
    uniq = []
    for x in out:
        if x not in uniq:
            uniq.append(x)
    return uniq[:limit]
